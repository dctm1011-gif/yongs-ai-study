import { getStore } from "@netlify/blobs";
import { createLogger, corsHeaders } from './_utils.mjs';
import { initializeApp } from 'firebase/app';
import { getDatabase, ref, set } from 'firebase/database';

export const config = {
  schedule: '0 21 * * *',
};

const log = createLogger('toefl-problems');

const firebaseConfig = {
  apiKey: process.env.FIREBASE_API_KEY,
  authDomain: process.env.FIREBASE_AUTH_DOMAIN,
  databaseURL: process.env.FIREBASE_DATABASE_URL,
  projectId: process.env.FIREBASE_PROJECT_ID,
  storageBucket: process.env.FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.FIREBASE_MESSAGING_SENDER_ID,
  appId: process.env.FIREBASE_APP_ID,
};

/**
 * Serves today's TOEFL problems (Reading, Writing, Speaking, Listening)
 * Data is dynamically generated by generate_toefl.py and stored in toefl/index.html
 */
export default async (req) => {
  const cors = corsHeaders();

  if (req.method === "OPTIONS") {
    return new Response(null, { status: 204, headers: cors });
  }

  try {
    log.log('Processing request', { method: req.method });

    if (req.method === "GET") {
      const store = getStore({ name: "toefl-problems", consistency: "strong" });

      // Try to get cached problems
      const cached = await store.get("today", { type: "json" }).catch(() => null);

      if (cached && cached.date === getTodayDate()) {
        log.log('GET successful (cached)', { date: cached.date });

        // Also save to Firebase
        const app = initializeApp(firebaseConfig);
        const db = getDatabase(app);
        await set(ref(db, `toefl/problems/${cached.date}`), cached);

        return Response.json(cached, { headers: cors });
      }

      // If not cached or stale, fetch from toefl/index.html
      try {
        const htmlResponse = await fetch(`${getBaseUrl()}/toefl/index.html`);
        if (!htmlResponse.ok) {
          throw new Error('Failed to fetch toefl/index.html');
        }

        const html = await htmlResponse.text();
        const problems = extractToeflProblems(html);

        // Cache the problems
        await store.set("today", JSON.stringify(problems));

        // Save to Firebase
        const app = initializeApp(firebaseConfig);
        const db = getDatabase(app);
        await set(ref(db, `toefl/problems/${problems.date}`), {
          ...problems,
          timestamp: new Date().toISOString(),
        });

        log.log('GET successful (fresh)', { date: problems.date });
        return Response.json(problems, { headers: cors });
      } catch (error) {
        log.warn('Failed to fetch fresh problems, returning cached', { error: error.message });
        if (cached) {
          return Response.json(cached, { headers: cors });
        }
        throw error;
      }
    }

    if (req.method === "POST") {
      const problems = await req.json();
      const store = getStore({ name: "toefl-problems", consistency: "strong" });
      await store.set("today", JSON.stringify(problems));

      // Save to Firebase
      const app = initializeApp(firebaseConfig);
      const db = getDatabase(app);
      await set(ref(db, `toefl/problems/${problems.date}`), {
        ...problems,
        timestamp: new Date().toISOString(),
      });

      log.log('POST successful', { date: problems.date });
      return Response.json({ ok: true, timestamp: new Date().toISOString() }, { headers: cors });
    }

    log.error('Unsupported method', { method: req.method });
    return new Response("Method not allowed", { status: 405, headers: cors });
  } catch (error) {
    log.error('Request failed', { message: error.message });
    return Response.json(
      {
        error: error.message,
        timestamp: new Date().toISOString(),
        sections: getDefaultProblems()
      },
      { status: 500, headers: cors }
    );
  }
};

/**
 * Extract TOEFL problems from HTML content
 */
function extractToeflProblems(html) {
  const problems = {
    date: getTodayDate(),
    reading: null,
    writing: null,
    speaking: null,
    listening: null,
  };

  // Extract READING
  const readingMatch = html.match(/const READING = (\{[^}]+(?:\{[^}]*\}[^}]*)*\});/);
  if (readingMatch) {
    try {
      problems.reading = JSON.parse(readingMatch[1]);
    } catch (e) {
      console.warn('Failed to parse READING:', e.message);
    }
  }

  // Extract WRITING
  const writingMatch = html.match(/const WRITING = (\{[^}]+(?:\{[^}]*\}[^}]*)*(?:\[[^\]]*\][^}]*)*\});/);
  if (writingMatch) {
    try {
      problems.writing = JSON.parse(writingMatch[1]);
    } catch (e) {
      console.warn('Failed to parse WRITING:', e.message);
    }
  }

  // Extract SPEAKING
  const speakingMatch = html.match(/const SPEAKING = (\{[^}]+(?:\[[^\]]*\][^}]*)*\});/);
  if (speakingMatch) {
    try {
      problems.speaking = JSON.parse(speakingMatch[1]);
    } catch (e) {
      console.warn('Failed to parse SPEAKING:', e.message);
    }
  }

  // Extract LISTENING
  const listeningMatch = html.match(/const LISTENING = (\{[^}]+(?:\{[^}]*\}[^}]*)*\});/);
  if (listeningMatch) {
    try {
      problems.listening = JSON.parse(listeningMatch[1]);
    } catch (e) {
      console.warn('Failed to parse LISTENING:', e.message);
    }
  }

  return problems;
}

/**
 * Get today's date in YYYY-MM-DD format
 */
function getTodayDate() {
  const now = new Date();
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')}`;
}

/**
 * Get base URL for fetching toefl/index.html
 */
function getBaseUrl() {
  if (process.env.URL) {
    return process.env.URL.replace(/\/$/, '');
  }
  return 'https://illustrious-cuchufli-7c4e58.netlify.app';
}

/**
 * Default problems if nothing is available
 */
function getDefaultProblems() {
  return {
    date: getTodayDate(),
    reading: {
      title: "Default Reading",
      passage: "Loading problems...",
      questions: [{ q: "Please refresh to load today's problems", options: ["A", "B", "C", "D"], answer: 0, explanation: "Loading..." }]
    },
    writing: {
      prompt: "Loading writing prompt...",
      structure: {},
      useful_phrases: []
    },
    speaking: {
      prompt: "Loading speaking prompt...",
      useful_expressions: [],
      sample_points: []
    },
    listening: {
      script: "Loading listening script...",
      questions: []
    }
  };
}
